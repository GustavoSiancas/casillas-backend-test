import { Consumer } from "src/consumer/consumer.entity";
import { Payment } from "src/payments/payments.entity";
import { Column, CreateDateColumn, DeleteDateColumn, Entity, JoinColumn, OneToMany, OneToOne, PrimaryGeneratedColumn, UpdateDateColumn } from "typeorm";

export enum MailboxStatus {
    ACTIVE = "ACTIVE",
    INACTIVE = "INACTIVE"
}

@Entity('mailbox')
export class Mailbox {
    @PrimaryGeneratedColumn()
    id: number; // autogenerated primary key

    @Column()
    mail_number: string; // mailbox number as fake id

    @OneToOne(() => Consumer, consumer => consumer.mailbox)
    @JoinColumn({
        name: "consumer_id"
    })
    consumer: Consumer;

    @OneToMany(() => Payment, payment => payment.mailbox)
    payments: Payment[];

    @Column({
        type: 'enum',
        enum: MailboxStatus,
        default: MailboxStatus.ACTIVE
    })
    status: MailboxStatus; // status of the mailbox, either ACTIVE or INACTIVE



    @CreateDateColumn()
    createdAt: Date;

    @UpdateDateColumn()
    updatedAt: Date;

    @DeleteDateColumn()
    deletedAt: Date; 
}