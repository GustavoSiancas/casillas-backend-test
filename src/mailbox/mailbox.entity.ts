import { Consumer } from "src/consumer/consumer.entity";
import { Payment } from "src/payments/payments.entity";
import { Column, CreateDateColumn, DeleteDateColumn, Entity, JoinColumn, OneToMany, ManyToOne, PrimaryGeneratedColumn, UpdateDateColumn, Unique } from "typeorm";

export enum MailboxStatus {
    ACTIVE = "ACTIVE",
    INACTIVE = "INACTIVE"
}

export enum MailboxType {
    MIRAFLORES = "MIRAFLORES",
    LIMACENTRO = "LIMACENTRO",
}

@Entity('mailbox')
@Unique("UQ_MAILBOX_CONSUMER_TYPE", ["consumer", "mailboxType"])
export class Mailbox {
    @PrimaryGeneratedColumn()
    id: number; // autogenerated primary key

    @Column()
    mail_number: string; // mailbox number as fake id

    @ManyToOne(() => Consumer, consumer => consumer.mailboxs)
    @JoinColumn({
        name: "consumer_id"
    })
    consumer: Consumer;

    @OneToMany(() => Payment, payment => payment.mailbox)
    payments: Payment[];

    @Column(
        {
            type: 'enum',
            enum: MailboxType
        }
    )
    mailboxType: MailboxType; // type of the mailbox, either MIRAFLORES or LIMACENTRO

    @Column({
        type: 'enum',
        enum: MailboxStatus,
        default: MailboxStatus.ACTIVE
    })
    status: MailboxStatus; // status of the mailbox, either ACTIVE or INACTIVE

    @CreateDateColumn()
    createdAt: Date;

    @UpdateDateColumn()
    updatedAt: Date;

    @DeleteDateColumn()
    deletedAt: Date; 
}